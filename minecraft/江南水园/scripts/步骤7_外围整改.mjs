// ── 贴壁假山：北墙西段、东墙中段 ──
function 假山(J, cx, cz, rx, rz, 峰表) {
  for (let x = cx - rx; x <= cx + rx; x++) for (let z = cz - rz; z <= cz + rz; z++) {
    const e = ((x - cx) / rx) ** 2 + ((z - cz) / rz) ** 2; if (e > 1) continue;
    let h = 0; for (const [px, pz, ph, sig] of 峰表) h = Math.max(h, ph * Math.exp(-(((x - px) ** 2 + (z - pz) ** 2) / (2 * sig * sig))));
    h *= Math.max(0, 1.1 - e);
    const hi = Math.max(0, Math.round(h));
    for (let y = 地面; y < 地面 + hi; y++) {
      if (y >= 地面 + hi - 2 && ((x * 31 + z * 17 + y * 13) >>> 0) % 100 < 14) continue;
      J.放(x, y, z, 选石(x, y, z)); 记('山', x, y, z, 选石(x, y, z));
      if (y >= 地面 + hi - 2) 排除.add(x + ',' + z);
    }
  }
}
