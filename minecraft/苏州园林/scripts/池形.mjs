/**
 * 池形：全园大水池的共享几何判定。
 * 所有需要与水面/岸线打交道的步骤（桥、舫、廊、假山、植被）必须引用本模块，
 * 保证与步骤1 实际施工完全一致。
 */
const 椭圆 = (x, z, cx, cz, rx, rz) => ((x - cx) / rx) ** 2 + ((z - cz) / rz) ** 2;
function 抖动(x, z) {
  let h = (x * 374761393 + z * 668265263) >>> 0; h = (h ^ (h >> 13)) * 1274126177 >>> 0;
  return ((h % 1000) / 1000 - 0.5) * 0.12;
}
export function 池内(x, z) {
  const j = 抖动(x, z);
  return 椭圆(x, z, -30, -10, 40, 32) + j <= 1 || 椭圆(x, z, -55, 8, 18, 14) + j <= 1 ||
         椭圆(x, z, -5, -30, 14, 12) + j <= 1 || 椭圆(x, z, -64, -24, 10, 10) + j <= 1;
}
export function 岛内(x, z) { return 椭圆(x, z, -8, -14, 7, 6) <= 1 || 椭圆(x, z, -40, -4, 6, 5) <= 1; }
export function 水体(x, z) { return 池内(x, z) && !岛内(x, z); }
/** 岸线：本身非水但四邻含水的陆地格 */
export function 岸线(x, z) {
  return !水体(x, z) && (水体(x + 1, z) || 水体(x - 1, z) || 水体(x, z + 1) || 水体(x, z - 1));
}
