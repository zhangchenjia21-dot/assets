/**
 * 地势：全园地形高度的单一事实来源。
 * 丘1 为步骤1 已施工的西部土山；丘2 为步骤8 补塑的余脉与微起伏。
 * 任何需要"实际地表高度"的步骤（植被、道路、假山接口）必须查 地表高()，
 * 避免把树种进丘体或把铺装悬空。
 */
export const 丘1 = [[-115, -30, 22, 18, 10], [-112, 8, 15, 12, 7]];
export const 丘2 = [
  [-108, -64, 10, 7, 4],  // 西北余脉·主阜
  [-98, -74, 9, 6, 3],    // 西北余脉·次阜
  [120, -90, 12, 8, 2],   // 东北疏林微起伏
  [80, -110, 10, 6, 2],
  [130, -70, 8, 6, 1],
];
export function 丘高(x, z, 丘表) {
  let h = 0;
  for (const [cx, cz, rx, rz, 峰] of 丘表) {
    const e = ((x - cx) / rx) ** 2 + ((z - cz) / rz) ** 2;
    if (e <= 1) h = Math.max(h, Math.round((1 - e) * 峰));
  }
  return h;
}
/** 实际地表（草面）所在 y；平地恒 63 */
export function 地表高(x, z) { return 63 + Math.max(丘高(x, z, 丘1), 丘高(x, z, 丘2)); }
