/** 红枫：栗木干 + 红杜鹃叶团，按地表高落位（西部土山秋色） */
function 红枫(J, x, z, seed) {
  const 基 = 地表高(x, z);
  const rnd = 随机(seed);
  const 高 = 3 + Math.floor(rnd() * 2);
  for (let y = 基 + 1; y <= 基 + 高; y++) J.放(x, y, z, 'minecraft:dark_oak_log[axis=y]');
  const 顶 = 基 + 高;
  for (let dx = -2; dx <= 2; dx++) for (let dz = -2; dz <= 2; dz++) for (let dy = 0; dy <= 1; dy++)
    if (Math.abs(dx) + Math.abs(dz) + dy * 0.5 <= 3.2) J.放(x + dx, 顶 + dy, z + dz, M.花叶);
}
