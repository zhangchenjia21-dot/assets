const 折线排 = (points, 半宽) => {
  for (let i = 0; i < points.length - 1; i++) {
    let [ax, az] = points[i]; const [bx, bz] = points[i + 1];
    const dx = Math.sign(bx - ax), dz = Math.sign(bz - az);
    for (;;) {
      for (let d = -半宽; d <= 半宽; d++) 排除.add((ax + (dz ? d : 0)) + ',' + (az + (dx ? d : 0)));
      if (ax === bx && az === bz) break;
      ax += dx; az += dz;
    }
  }
};
